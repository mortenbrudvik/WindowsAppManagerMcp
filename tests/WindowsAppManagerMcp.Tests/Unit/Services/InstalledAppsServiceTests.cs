namespace WindowsAppManagerMcp.Tests.Unit.Services;

/// <summary>
/// InstalledAppsService (roadmap M6.5): the Applications folder as list_installed_apps and the launch's friendly names see
/// it, and a packaged app's program read from its manifest. The folder and the manifests are a fake; nothing is read from
/// the real shell or started.
/// </summary>
public class InstalledAppsServiceTests
{
    private const string Calculator = "Microsoft.WindowsCalculator_8wekyb3d8bbwe!App";
    private const string CalculatorFamily = "Microsoft.WindowsCalculator_8wekyb3d8bbwe";

    private readonly Mock<INativeAppsWrapper> _native = new(MockBehavior.Strict);
    private readonly ManualClock _clock = new();
    private List<AppsFolderEntry>? _folder =
    [
        new("Word", "Microsoft.Office.WINWORD.EXE.15", TargetPath: @"C:\Program Files\Microsoft Office\root\Office16\WINWORD.EXE"),
        new("Kalkulator", Calculator, CalculatorFamily),
        new("Settings", "windows.immersivecontrolpanel_cw5n1h2txyewy!microsoft.windows.immersivecontrolpanel", "windows.immersivecontrolpanel_cw5n1h2txyewy"),
        new("Settings", "Microsoft.AutoGenerated.{8E66BD49-EE30-5B64-E59D-4838E1A8063F}", TargetPath: @"C:\Program Files\TortoiseGit\bin\TortoiseGitProc.exe"),
        new("Terminal", "Microsoft.WindowsTerminal_8wekyb3d8bbwe!App", "Microsoft.WindowsTerminal_8wekyb3d8bbwe"),
        new("Python 3.12 (64-bit)", @"C:\Python312\python.exe", TargetPath: @"C:\Python312\python.exe"),
        new("Kalkulator", Calculator, CalculatorFamily),
        new("Google Chrome", "Chrome", TargetPath: @"C:\Program Files\Google\Chrome\Application\chrome.exe"),
        new("Google Chrome", "Chrome.Canary", TargetPath: @"C:\Program Files\Google\Chrome\Application\chrome.exe"),
    ];

    public InstalledAppsServiceTests()
    {
        _native.Setup(n => n.EnumerateAppsFolder()).Returns(() => _folder);
    }

    private InstalledAppsService CreateSut() => new(_native.Object, _clock);

    [Fact]
    public void List_PutsPackagedAppsFirst_ThenByName_EachAppIdOnce()
    {
        var listing = CreateSut().List(nameFilter: null, limit: 25);

        listing.Unreadable.Should().BeFalse();
        listing.Total.Should().Be(8, "Kalkulator is listed twice by the folder");
        listing.Truncated.Should().BeFalse();
        listing.Apps.Select(a => a.Name).Should().Equal(
            "Kalkulator", "Settings", "Terminal", "Google Chrome", "Google Chrome", "Python 3.12 (64-bit)", "Settings", "Word");
        listing.Apps[0].Should().Be(new InstalledApp("Kalkulator", Calculator, Packaged: true, Path: null));
        listing.Apps.Single(a => a.AppId == "Chrome").Should().Be(
            new InstalledApp("Google Chrome", "Chrome", Packaged: false, Path: @"C:\Program Files\Google\Chrome\Application\chrome.exe"));
    }

    [Fact]
    public void List_FiltersByPartOfTheNameOrTheAppId_CaseInsensitive()
    {
        var sut = CreateSut();

        sut.List("kalk", 25).Apps.Select(a => a.AppId).Should().Equal(Calculator);
        sut.List("WINWORD", 25).Apps.Select(a => a.Name).Should().Equal("Word");
        sut.List("settings", 25).Total.Should().Be(2);
    }

    [Fact]
    public void List_CutsAtTheLimit_AndSaysSo()
    {
        var listing = CreateSut().List(null, 3);

        listing.Apps.Should().HaveCount(3);
        listing.Total.Should().Be(8);
        listing.Truncated.Should().BeTrue();
    }

    [Fact]
    public void List_AFolderThatCannotBeRead_IsEmptyAndUnreadable()
    {
        _folder = null;

        var listing = CreateSut().List(null, 25);

        listing.Unreadable.Should().BeTrue();
        listing.Apps.Should().BeEmpty();
        listing.Total.Should().Be(0);
    }

    [Fact]
    public void TheFolder_IsReadOnceIn30Seconds()
    {
        var sut = CreateSut();

        sut.List(null, 25);
        sut.FindByName("Word");
        _clock.Advance(TimeSpan.FromSeconds(29));
        sut.FindByAppId("Chrome");
        _native.Verify(n => n.EnumerateAppsFolder(), Times.Once);

        _clock.Advance(TimeSpan.FromSeconds(2));
        sut.List(null, 25);
        _native.Verify(n => n.EnumerateAppsFolder(), Times.Exactly(2));
    }

    [Fact]
    public void AFolderThatCouldNotBeRead_IsReadAgainNextTime()
    {
        _folder = null;
        var sut = CreateSut();
        sut.List(null, 25).Unreadable.Should().BeTrue();

        _folder = [new AppsFolderEntry("Word", "Microsoft.Office.WINWORD.EXE.15")];

        sut.List(null, 25).Apps.Should().ContainSingle();
    }

    [Theory]
    [InlineData("Kalkulator")]
    [InlineData("kalkulator")]
    [InlineData("  KALKULATOR ")]
    public void FindByName_IsAnExactCaseInsensitiveMatch_EachAppOnce(string name)
    {
        CreateSut().FindByName(name)!.Select(a => a.AppId).Should().Equal(Calculator);
    }

    [Theory]
    [InlineData("Kalk")]
    [InlineData("Kalkulatorr")]
    [InlineData("Calculator")]
    public void FindByName_NeverMatchesPartOfAName(string name)
    {
        CreateSut().FindByName(name).Should().BeEmpty("only exact display names count, so a planted shortcut cannot steer a near name");
    }

    [Fact]
    public void FindByName_TwoAppsOfTheSameName_AreBothReturned()
    {
        CreateSut().FindByName("Settings")!.Should().HaveCount(2);
    }

    [Fact]
    public void FindByName_TwoShortcutsToTheSameProgram_AreOneApp()
    {
        CreateSut().FindByName("Google Chrome")!.Should().ContainSingle();
    }

    [Fact]
    public void FindByName_AFolderThatCannotBeRead_IsNull()
    {
        _folder = null;

        CreateSut().FindByName("Word").Should().BeNull();
    }

    [Fact]
    public void FindByAppId_IsCaseInsensitive()
    {
        CreateSut().FindByAppId("chrome")!.Path.Should().EndWith("chrome.exe");
        CreateSut().FindByAppId("Nothing.Like.It").Should().BeNull();
    }

    private const string TerminalManifest = """
        <?xml version="1.0" encoding="utf-8"?>
        <Package xmlns="http://schemas.microsoft.com/appx/manifest/foundation/windows10">
          <Applications>
            <Application Id="App" Executable="WindowsTerminal.exe" EntryPoint="Windows.FullTrustApplication" />
          </Applications>
        </Package>
        """;

    private const string NotepadManifest = """
        <Package xmlns="http://schemas.microsoft.com/appx/manifest/foundation/windows10">
          <Applications>
            <Application Id="Other" Executable="Helper.exe" />
            <Application Id="App" Executable="Notepad\Notepad.exe" />
          </Applications>
        </Package>
        """;

    private const string ResourceManifest = """
        <Package xmlns="http://schemas.microsoft.com/appx/manifest/foundation/windows10"><Resources /></Package>
        """;

    [Fact]
    public void ProgramOf_IsTheExecutableOfTheAppInItsManifest()
    {
        _native.Setup(n => n.ReadPackageManifests("Microsoft.WindowsNotepad_8wekyb3d8bbwe")).Returns([ResourceManifest, NotepadManifest]);
        _native.Setup(n => n.ReadPackageManifests("Microsoft.WindowsTerminal_8wekyb3d8bbwe")).Returns([TerminalManifest]);
        var sut = CreateSut();

        sut.ProgramOf(new PackagedAppId("Microsoft.WindowsNotepad_8wekyb3d8bbwe", "App")).Should().Be("Notepad.exe");
        sut.ProgramOf(new PackagedAppId("Microsoft.WindowsNotepad_8wekyb3d8bbwe", "other")).Should().Be("Helper.exe");
        sut.ProgramOf(new PackagedAppId("Microsoft.WindowsTerminal_8wekyb3d8bbwe", "App")).Should().Be("WindowsTerminal.exe");
    }

    [Theory]
    [InlineData(null)]
    [InlineData("not xml")]
    [InlineData("""<Package xmlns="http://schemas.microsoft.com/appx/manifest/foundation/windows10"><Applications><Application Id="Other" Executable="a.exe" /></Applications></Package>""")]
    [InlineData("""<Package xmlns="http://schemas.microsoft.com/appx/manifest/foundation/windows10"><Applications><Application Id="App" /></Applications></Package>""")]
    [InlineData("""<!DOCTYPE p [<!ENTITY x "y">]><Package><Applications><Application Id="App" Executable="&x;.exe" /></Applications></Package>""")]
    public void ProgramOf_IsNull_WhenTheManifestDoesNotNameTheAppsProgram(string? manifest)
    {
        _native.Setup(n => n.ReadPackageManifests(It.IsAny<string>())).Returns(manifest == null ? null : [manifest]);

        CreateSut().ProgramOf(new PackagedAppId("Vendor.App_8wekyb3d8bbwe", "App")).Should().BeNull();
    }
}
